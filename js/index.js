const languageToggle = document.querySelector("[data-language-toggle]");
let currentLanguage = localStorage.getItem("site-language") || "tr";

function applyLanguage(language) {
    currentLanguage = language;
    document.documentElement.lang = language;
    document.title = translations[language]["meta.title"];
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const translation = translations[language][element.dataset.i18n];
        if (element.tagName === "META") {
            element.setAttribute("content", translation);
        } else {
            element.innerHTML = translation;
        }
    });
    document.querySelector("[data-cv-link]").setAttribute(
        "href",
        language === "tr"
            ? "images/Serhan%20Yaman%20Durmu%C5%9F%20CV%20Tr.pptx"
            : "images/Serhan%20Yaman%20Durmu%C5%9F%20CV%20%C4%B0ng.pptx"
    );
    document.querySelector(".desktop-nav").setAttribute("aria-label", language === "tr" ? "Ana navigasyon" : "Main navigation");
    document.querySelector(".menu-toggle").setAttribute("aria-label", language === "tr" ? "Menüyü aç" : "Open menu");
    languageToggle.textContent = language === "tr" ? "EN" : "TR";
    languageToggle.setAttribute("aria-label", language === "tr" ? "Switch to English" : "Türkçeye geç");
    localStorage.setItem("site-language", language);
}

languageToggle?.addEventListener("click", () => {
    applyLanguage(currentLanguage === "tr" ? "en" : "tr");
});

applyLanguage(currentLanguage);

const menuToggle = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".desktop-nav");
const navigationLinks = document.querySelectorAll(".desktop-nav a");

menuToggle?.addEventListener("click", () => {
    const isOpen = navigation.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
});

navigationLinks.forEach((link) => {
    link.addEventListener("click", () => {
        navigation.classList.remove("open");
        menuToggle?.setAttribute("aria-expanded", "false");
    });
});

const revealElements = document.querySelectorAll(".reveal");
const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
    });
}, { threshold: 0.12 });

revealElements.forEach((element) => revealObserver.observe(element));

const sections = document.querySelectorAll("main section[id]");
const navObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        navigationLinks.forEach((link) => {
            link.classList.toggle("active", link.getAttribute("href") === `#${entry.target.id}`);
        });
    });
}, { rootMargin: "-35% 0px -55% 0px" });

sections.forEach((section) => navObserver.observe(section));
